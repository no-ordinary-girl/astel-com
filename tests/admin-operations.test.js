const assert = require('node:assert/strict');
const pay = require('../js/admin-payments.js');
const warranty = require('../js/admin-warranty.js');
const finance = require('../js/order-finance.js');
const mockStorage = () => ({ map:new Map(), getItem(k){return this.map.get(k)||null},setItem(k,v){this.map.set(k,String(v))} });
const o = { orderId:'AK-9001', statusCode:'completed', subtotal:50000, recognizedRevenue:50000, payment:'Банківський переказ', items:[{id:'modem',title:'Модем',qty:10}] };
const st = mockStorage();
assert.equal(pay.summary(o,st).remaining,5000000);
const pending = pay.add(o,{type:'payment',amount:'20000',method:'bank',reference:'TRANSFER-123'},st);
assert.equal(pay.summary(o,st).received,0, 'Pending is not paid');
assert.equal(pay.summary(o,st).pending,2000000);
pay.changeState(o,pending.id,'confirmed',st);
assert.equal(pay.summary(o,st).received,2000000);
assert.equal(pay.summary(o,st).remaining,3000000);
assert.equal(pay.status(o,st),'partial');
const second = pay.add(o,{type:'payment',amount:'30000',method:'bank'},st);
pay.changeState(o,second.id,'confirmed',st);
assert.equal(pay.status(o,st),'paid');
const tooMuch = pay.add(o,{type:'payment',amount:'500',method:'bank'},st);
pay.changeState(o,tooMuch.id,'confirmed',st);
assert.equal(pay.status(o,st),'overpaid');
const refund = pay.add(o,{type:'refund',amount:'500',method:'bank'},st);
pay.changeState(o,refund.id,'confirmed',st);
assert.equal(pay.status(o,st),'paid');
pay.changeState(o,pending.id,'void',st);
assert.equal(pay.status(o,st),'partial');
assert.equal(finance.contribution(o),50000,'No payment side effects on revenue');
const ws=mockStorage();
const initial = warranty.save(o,{productId:'modem',reason:'Несправність після отримання',resolution:'replacement',outcome:'open',replacementTtn:''},null,ws);
assert.equal(warranty.forOrder(o.orderId,ws).length,1);
warranty.save(o,{productId:'modem',reason:'Несправність після отримання',resolution:'replacement',outcome:'replacement_sent',replacementTtn:'20450817263451'},initial.record.id,ws);
assert.equal(warranty.forOrder(o.orderId,ws)[0].outcome,'replacement_sent');
assert.equal(o.statusCode,'completed');
assert.equal(o.recognizedRevenue,50000);
assert.throws(()=>warranty.save({...o,statusCode:'processing'}, {productId:'modem',reason:'Несправність',resolution:'repair',outcome:'open'},null,ws), /лише до виконаного/);
assert.throws(()=>warranty.save(o, {productId:'modem',reason:'Too',resolution:'repair',outcome:'open'},null,ws), /щонайменше/);
console.log('payment and warranty checks OK');
