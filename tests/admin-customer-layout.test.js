#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
const admin = fs.readFileSync(path.join(root, "js/admin.js"), "utf8");
const css = fs.readFileSync(path.join(root, "css/admin-customers.css"), "utf8");
assert.match(admin, /admin-client-order__note-panel/, "Notes expand inside a specific order");
assert.match(admin, /admin-client-order__row/, "Orders have independent headers");
assert.match(admin, /data-client-notes-for-order/, "Notes are opened directly from an order");
assert.match(admin, /data-client-note-form/, "The order has its own note form");
assert.match(admin, /data-order-id/, "Note form is tied to order ID");
assert.doesNotMatch(admin, /data-client-note-order|data-client-view=|data-client-panel=/, "No redundant tabs or order dropdown");
assert.match(admin, /data-toggle-client-attention/, "Gray/red marker is kept beside avatar");
assert.match(admin, /<svg class="admin-client-expand__arrow"/, "Collapse icon is a centered inline SVG");
assert.match(css, /admin-client-order__row/, "Order-first layout styles are present");
assert.match(css, /admin-client-order__note-panel/, "Notes belong to order visually");
assert.match(css, /admin-client-expand__arrow/, "Chevron has a fixed 14px viewBox");
assert.match(css, /@media \(max-width: 820px\)/, "Responsive order layout is retained");
assert.doesNotMatch(css, /admin-client-details__tabs|admin-client-details__columns/, "Old tabbed/two-column layouts are removed");
console.log("PASS: order-first client history, contextual notes, and centered chevron");
