#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'js/products-data.js'),'utf8');
const admin=fs.readFileSync(path.join(root,'js/admin.js'),'utf8');
const editorSource=fs.readFileSync(path.join(root,'js/admin-new-product.js'),'utf8');
const css=fs.readFileSync(path.join(root,'css/admin-photos.css'),'utf8');
const html=fs.readFileSync(path.join(root,'admin.html'),'utf8');
const store=new Map();
const localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const create=()=>vm.createContext({localStorage});
let ctx=create();vm.runInContext(source,ctx);
const run=(code)=>vm.runInContext(code,ctx);
const previousTitle=run('PRODUCTS_DATA["com-900-485"].title');
const previousTitleEn=run('PRODUCTS_DATA["com-900-485"].titleEn');
run(`CatalogManager.updateProduct('com-900-485',{title:'Оновлений модем COM-900',titleEn:'Updated COM-900 Modem'})`);
assert.equal(run('PRODUCTS_DATA["com-900-485"].title'),'Оновлений модем COM-900');
assert.equal(run('PRODUCTS_DATA["com-900-485"].titleEn'),'Updated COM-900 Modem');
ctx=create();vm.runInContext(source,ctx);
assert.equal(run('PRODUCTS_DATA["com-900-485"].title'),'Оновлений модем COM-900');
assert.equal(run('PRODUCTS_DATA["com-900-485"].titleEn'),'Updated COM-900 Modem');
assert.throws(()=>run("CatalogManager.updateProduct('com-900-485',{title:'X'})"),/Назва товару/);
assert.throws(()=>run("CatalogManager.updateProduct('com-900-485',{titleEn:'Український текст'})"),/англійською/);
assert.match(admin,/extractProductNames\(form\)/);
assert.match(editorSource,/function extractProductNames\(form\)/);
assert.match(editorSource,/Назва таблиці/);
assert.doesNotMatch(editorSource,/>Тип таблиці/);
assert.match(html,/data-editor-field-lang="en">Назва товару[\s\S]*?name="titleEn"/);
assert.match(css,/\.admin-editor-language-context/);
assert.match(css,/\.admin-product-name-grid/);
console.log('PASS: editable bilingual product names persist, validate, and use clear language context');
