#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const editor=require('../js/admin-new-product.js');
assert.equal(editor.tableType('Технічні характеристики','Technical Specifications'),'tech');
assert.equal(editor.tableType('Основні характеристики','General Specifications'),'general');
assert.equal(editor.tableType('Дані пристрою','Device data'),'custom');
const classSet=()=>{const s=new Set();return {add:x=>s.add(x),remove:x=>s.delete(x),contains:x=>s.has(x)};};
const input=value=>({value,placeholder:'',classList:classSet(),attrs:{},setAttribute(k,v){this.attrs[k]=v;},removeAttribute(k){delete this.attrs[k];},getAttribute(k){return this.attrs[k];},focus(){this.focused=true;},scrollIntoView(){this.scrolled=true;}});
const ukLabel=input('Тестовий параметр'),enLabel=input('');
const ukValue=input('Нове значення'),enValue=input('');
const row={querySelector:s=>({'[data-spec-label]':ukLabel,'[data-spec-label-en]':enLabel,'[data-spec-value]':ukValue,'[data-spec-value-en]':enValue})[s]};
const ukTitle=input('Технічні характеристики'),enTitle=input('Technical Specifications');
const section={querySelector:s=>({'[data-spec-title]':ukTitle,'[data-spec-title-en]':enTitle})[s],querySelectorAll:s=>s==='.admin-spec-row'?[row]:[]};
const tab=(language)=>({dataset:{editorLang:language},setAttribute(k,v){this[k]=v;}});
const tabs=[tab('uk'),tab('en')];
const form={dataset:{editorLanguage:'uk'},querySelector:s=>({'[name="description"]':input(''),'[name="descriptionEn"]':input('')})[s],querySelectorAll:s=>({'.admin-translation-missing':[],'.admin-spec-section':[section],'.admin-document-row':[],'[data-editor-lang]':tabs})[s]||[]};
assert.equal(editor.validateTranslations(form),false);
assert.equal(form.dataset.editorLanguage,'en');
assert.equal(enLabel.getAttribute('aria-invalid'),'true');
assert.match(enLabel.placeholder,/Перекладіть «Тестовий параметр» англійською/);
assert.equal(enLabel.focused,true);
assert.equal(enValue.getAttribute('aria-invalid'),'true');
enLabel.value='Test parameter';enValue.value='New value';
assert.equal(editor.validateTranslations(form),true);
// Verify that product updates preserve the section data used by the public product page.
const source=fs.readFileSync(path.join(root,'js/products-data.js'),'utf8');
const store=new Map();
const storage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k)};
const ctx=vm.createContext({localStorage:storage});vm.runInContext(source,ctx);
const sections=[{type:'tech',rows:[{label:ukLabel.value,labelEn:enLabel.value,value:ukValue.value,valueEn:enValue.value}]}];
vm.runInContext(`CatalogManager.updateProduct('com-900-485',${JSON.stringify({specSections:sections,techSpecs:[],generalSpecs:[]})})`,ctx);
assert.equal(vm.runInContext(`PRODUCTS_DATA['com-900-485'].specSections[0].rows[0].labelEn`,ctx),'Test parameter');
const page=fs.readFileSync(path.join(root,'product.html'),'utf8');
assert.match(page,/\$\{extraSpecsSection\}/);
assert.match(page,/\$\{renderTableRows\(section\.rows \|\| \[\]\)\}/);
const admin=fs.readFileSync(path.join(root,'js/admin.js'),'utf8');
assert.match(admin,/if\(!AstelProductEditor\.validateTranslations\(form\)\)/);
assert.match(admin,/patch\.specSections=AstelProductEditor\.extractSections\(form\)/);
const css=fs.readFileSync(path.join(root,'css/admin-photos.css'),'utf8');
assert.match(css,/\.admin-editor-language-tabs\s*\{[^}]*width:\s*100%/);
assert.match(css,/\.admin-product-content-toggle\s*\{[^}]*inline-flex/);
console.log('PASS: inline table titles, guided English translation, draft save and storefront specifications');
