#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const finance=require('../js/order-finance.js');
const root=path.resolve(__dirname,'..');
const memory=new Map();
const localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const ctx=vm.createContext({localStorage});
vm.runInContext(fs.readFileSync(path.join(root,'js/products-data.js'),'utf8'),ctx);
const get=x=>vm.runInContext(x,ctx);
assert.equal(get('Object.keys(PRODUCTS_DATA).length'),15);
assert.equal(finance.acceptedGreen({payment:'Готівка',paymentStatus:'unpaid'}),true);
assert.equal(finance.acceptedGreen({payment:'Оплата банківською картою',paymentStatus:'unpaid'}),false);
assert.equal(finance.acceptedGreen({payment:'Оплата банківською картою',paymentStatus:'paid'}),false,'unverified localStorage value must not count as paid');
assert.equal(finance.acceptedGreen({orderId:'AK-x',payment:'Оплата банківською картою',paymentStatus:'paid',paymentVerification:{verified:true,provider:'liqpay',orderId:'AK-x',amount:43000,currency:'UAH'},subtotal:43000}),true);
assert.equal(finance.paymentLabel({payment:'Готівка'}),'Оплата при отриманні');
assert.match(finance.paymentLabel({payment:'Google Pay'}),/Очікує/);
let order={orderId:'AK-x',statusCode:'processing',subtotal:43000};
assert.equal(finance.contribution(order),0);
order=finance.transition(order,'completed');
assert.equal(finance.total([order]),43000);
order=finance.transition(order,'processing');
assert.equal(finance.total([order]),43000,'reopening should not remove or duplicate previously earned amount');
order=finance.transition(finance.transition(order,'shipped'),'completed');
assert.equal(finance.total([order]),43000,'repeated completion must not increment total');
order=finance.transition(order,'canceled');
assert.equal(finance.total([order]),0,'cancel reverses previously recognized revenue');
order=finance.transition({...order,subtotal:45000},'completed');
assert.equal(finance.total([order]),45000,'re-completion after cancellation credits once');
assert.equal(finance.total([{orderId:'AK-y',statusCode:'completed',subtotal:10000}]),10000,'legacy order migration');
assert.equal(finance.total([order,order]),45000,'duplicate history entries counted once');
let bad={customer:{firstName:'A',lastName:'B',phone:'123456789',email:'a@b.co'},delivery:{city:'Kyiv',branch:'Some street',carrierKey:'nova'},items:[{id:'p',price:4300,qty:10}]};
assert.equal(finance.validateEdits(bad.customer,bad.delivery,bad.items),43000);
assert.throws(()=>finance.validateEdits(bad.customer,bad.delivery,[{price:4300,qty:-5}]),/кількість/);
assert.throws(()=>finance.validateEdits({...bad.customer,email:'invalid'},bad.delivery,bad.items),/адреса/);
get('CatalogManager.updateProduct("com-900-485",{category:"nbiot",saleTermsCode:"retail"})');
assert.equal(get('PRODUCTS_DATA["com-900-485"].category'),'nbiot');
assert.equal(get('PRODUCTS_DATA["com-900-485"].minOrderQty'),1);
assert.equal(get('PRODUCTS_DATA["com-900-485"].saleTerms'),'Оптом і в роздріб');
const original=get('PRODUCTS_DATA["com-900-485"].images[0]');
const second=get('PRODUCTS_DATA["com-900-485"].images[1]');
get('CatalogManager.updateProduct("com-900-485",{images:[PRODUCTS_DATA["com-900-485"].images[1],PRODUCTS_DATA["com-900-485"].images[0]]})');
assert.equal(get('PRODUCTS_DATA["com-900-485"].images[0]'),second);
assert.equal(get('PRODUCTS_DATA["com-900-485"].image'),second);
assert.notEqual(original,second);
get(`CatalogManager.addProduct({id:'test-modem',title:'Test Modem',titleEn:'Test Modem',price:900,category:'gsm',saleTermsCode:'wholesale',inStock:true,images:['assets/images/logo-main.svg']})`);
assert.equal(get('Object.keys(PRODUCTS_DATA).length'),16);
assert.equal(get('PRODUCTS_DATA["test-modem"].minOrderQty'),10);
assert.equal(get('PRODUCTS_DATA["test-modem"].numericPrice'),900);
get('CatalogManager.applyOverrides()');
assert.equal(get('PRODUCTS_DATA["test-modem"].category'),'gsm');
assert.equal(get('PRODUCTS_DATA["com-900-485"].images[0]'),second);
assert.throws(()=>get('CatalogManager.addProduct({id:"test-modem",title:"abc",price:200,category:"gsm",saleTermsCode:"wholesale",images:["assets/images/logo-main.svg"]})'),/Унікальний/);
assert.throws(()=>get('CatalogManager.updateProduct("test-modem",{images:["javascript:alert(1)"]})'),/зображень/);
const catalog=fs.readFileSync(path.join(root,'products.html'),'utf8');
assert.doesNotMatch(catalog,/<article\s+class="product-card"/);
assert.match(catalog,/js\/products-catalog\.js/);
assert.match(catalog,/js\/products-data\.js/);
assert.match(fs.readFileSync(path.join(root,'js/products-catalog.js'),'utf8'),/Object\.values\(PRODUCTS_DATA\)/);
console.log('PASS: payment-driven acceptance, revenue transitions, catalog metadata, photo order, custom items and catalog renderer');
